"use server"

import { redirect } from "next/navigation"
import { auth } from "@/lib/auth"
import { prisma } from "@obravision/db"
import { createTenantClient } from "@obravision/db/rls-client"
import { obraSchema } from "@/lib/validations/obra"

// Default ObraStatus entries for new empresas
const DEFAULT_STATUSES = [
  { name: "Em execucao", color: "#1A6B5A" },
  { name: "Paralisada", color: "#EAB308" },
  { name: "Concluida", color: "#16A34A" },
]

export async function createEmpresa(formData: FormData) {
  const session = await auth()
  if (!session?.user?.id) {
    redirect("/login")
  }

  const nome = (formData.get("nome") as string)?.trim()
  if (!nome || nome.length === 0) {
    return { error: "Nome da empresa e obrigatorio" }
  }

  // Create empresa — tenantId generated by Prisma @default(cuid())
  const empresa = await prisma.empresa.create({
    data: {
      nome,
      members: {
        connect: { id: session.user.id },
      },
    },
  })

  // Update user: set empresaId, promote to ADMIN, advance onboardingStep to 1
  await prisma.user.update({
    where: { id: session.user.id },
    data: {
      empresaId: empresa.id,
      role: "ADMIN",
      onboardingStep: 1,
    },
  })

  // Create 3 default ObraStatus entries for this empresa
  await prisma.obraStatus.createMany({
    data: DEFAULT_STATUSES.map((s) => ({
      tenantId: empresa.tenantId,
      name: s.name,
      color: s.color,
      empresaId: empresa.id,
    })),
  })

  redirect("/onboarding/obra")
}

export async function createFirstObra(formData: FormData) {
  const session = await auth()
  if (!session?.user?.id || !session.user.empresaId) {
    redirect("/login")
  }

  const rawData = {
    nome: formData.get("nome") as string,
    logradouro: formData.get("logradouro") as string,
    numero: formData.get("numero") as string,
    cidade: formData.get("cidade") as string,
    estado: formData.get("estado") as string,
    cep: formData.get("cep") as string,
    tipo: formData.get("tipo") as string,
    area: formData.get("area") as string,
  }

  const result = obraSchema.safeParse(rawData)
  if (!result.success) {
    return { error: result.error.errors[0]?.message ?? "Dados invalidos" }
  }

  const data = result.data

  const empresa = await prisma.empresa.findUnique({
    where: { id: session.user.empresaId },
    include: { statuses: { take: 1 } },
  })

  if (!empresa) {
    return { error: "Empresa nao encontrada" }
  }

  const tenantClient = createTenantClient(empresa.tenantId)

  await tenantClient.obra.create({
    data: {
      tenantId: empresa.tenantId,
      nome: data.nome,
      logradouro: data.logradouro,
      numero: data.numero,
      cidade: data.cidade,
      estado: data.estado,
      cep: data.cep,
      tipo: data.tipo,
      area: data.area,
      empresaId: empresa.id,
      statusId: empresa.statuses[0]?.id ?? null,
      members: {
        create: {
          tenantId: empresa.tenantId,
          userId: session.user.id,
          role: "ADMIN",
        },
      },
    },
  })

  // Persist onboardingStep to DB immediately (RESEARCH.md pitfall 4)
  await prisma.user.update({
    where: { id: session.user.id },
    data: { onboardingStep: 2 },
  })

  redirect("/onboarding/equipe")
}

export async function completeOnboarding() {
  const session = await auth()
  if (!session?.user?.id) {
    redirect("/login")
  }

  await prisma.user.update({
    where: { id: session.user.id },
    data: { onboardingStep: 3 },
  })

  redirect("/dashboard")
}
